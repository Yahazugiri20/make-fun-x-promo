function text(str, x, y, scale, c) {
  let cx = x;
  for (const ch of str) {
    const g = G[ch] ?? G['?'];
    if (!g) { cx += 6 * scale; continue; }
    for (let ry = 0; ry < 7; ry++) {
      for (let rx = 0; rx < 5; rx++) {
        if (g[ry][rx] === '1') rect(cx + rx * scale, y + ry * scale, cx + (rx + 1) * scale, y + (ry + 1) * scale, c);
      }
    }
    cx += 6 * scale;
  }
}

