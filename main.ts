const W = 1600;
const H = 900;

const bg = (y) => {
  const t = y / H;
  return [Math.round(11 + 18 * t), Math.round(15 + 10 * t), Math.round(26 + 40 * t)];
};

const px = Buffer.alloc(W * H * 3);
for (let y = 0; y < H; y++) {
  const [r, g, b] = bg(y);
  for (let x = 0; x < W; x++) {
    const i = (y * W + x) * 3;
    px[i] = r; px[i + 1] = g; px[i + 2] = b;
  }
}

function rect(x0, y0, x1, y1, c) {
  for (let y = Math.max(0, y0 | 0); y < Math.min(H, y1 | 0); y++) {
    for (let x = Math.max(0, x0 | 0); x < Math.min(W, x1 | 0); x++) {
      const i = (y * W + x) * 3;
      px[i] = c[0]; px[i + 1] = c[1]; px[i + 2] = c[2];
    }
  }
}

function border(x0, y0, x1, y1, c, t = 3) {
  rect(x0, y0, x1, y0 + t, c);
  rect(x0, y1 - t, x1, y1, c);
  rect(x0, y0, x0 + t, y1, c);
  rect(x1 - t, y0, x1, y1, c);
}

